def normalize_subtitle_line(line):
    """부제 한 줄의 나열 기호를 '-'로 통일한다. 9·19처럼 숫자 사이의 '·'는 날짜 표기라 그대로 둔다."""
    return re.sub(r'(?<!\d)·|·(?!\d)', '-', line).strip()
