// 5. 생성기·검수기가 함께 사용하는 규칙 조회
function getPlatformRules(platform) {
  if (!Object.hasOwn(PLATFORM_RULES, platform)) {
    throw new Error(`지원하지 않는 플랫폼입니다: ${platform}`);
  }
  return { ...PLATFORM_RULES[platform], common_rules: COMMON_RULES };
}
module.exports = { getPlatformRules };
