import assert from 'node:assert/strict';
import fs from 'node:fs';
import {JSDOM} from 'jsdom';
import {createCoreClient,createWorkspaceCoreAdapter,fromCoreRevision,toRevisionInput} from '../assets/api.js';
const f=JSON.parse(fs.readFileSync(new URL('../integration/contract_v0_8/fixtures/vertical-slice-v0.8.json',import.meta.url)));
globalThis.document=new JSDOM().window.document;
const draft=fromCoreRevision(f.article,f.revision);
assert.equal(toRevisionInput(draft,7).body_html,f.revision.body_html);
assert.equal(toRevisionInput({...draft,bodyHtml:'<p>첫<s>삭제</s></p><p>다음<br>줄</p>'}).body_text,'첫\n다음\n줄');
const sent=[];
globalThis.fetch=async(url,opts)=>{sent.push({url,...opts});return{ok:true,json:async()=>({...f.revision,editor_state:JSON.parse(opts.body).editor_state})};};
const payload={workspace_id:f.workspace.id,article_id:f.article.id,input:toRevisionInput(draft,7)};
const client=createCoreClient({token:'test-token'});
const http=await client.saveArticle(payload);
const ipc=createCoreClient({ipc:{saveArticle:async p=>{assert.deepEqual(p,payload);return http;}}});
assert.deepEqual(await ipc.saveArticle(payload),http);
assert.equal(sent[0].url,`/api/core/v0.8/workspaces/${f.workspace.id}/articles/${f.article.id}/revisions`);
assert.equal(sent[0].headers.Authorization,'Bearer test-token');
assert.equal(JSON.parse(sent[0].body).expected_revision_no,7);
const bad=createCoreClient({ipc:{saveArticle:async()=>({error:{code:'REVISION_CONFLICT',message:'수정 충돌',retryable:false}})}});
await assert.rejects(()=>bad.saveArticle(payload),e=>e.code==='REVISION_CONFLICT'&&e.retryable===false);
await assert.rejects(()=>client.getArticle({workspace_id:'bad',article_id:f.article.id}),/UUID/);
const adapter=createWorkspaceCoreAdapter({client,workspaceId:f.workspace.id});
const saved=await adapter.request('/api/articles/save',{draft},draft);
assert.equal(saved.storageDraft.core_context.revision_id,f.revision.id);
assert.equal(saved.storageDraft.bodyHtml,draft.bodyHtml);
await assert.rejects(()=>adapter.request('/api/articles/x/versions',null,draft),/아직 정의되지/);
await assert.rejects(()=>adapter.request('/api/articles/save',{draft:{...draft,photos:[{id:'unregistered'}]}},draft),/MediaAsset/);
console.log('PASS Core DTO round trip, HTTP/IPC parity, revision guard, error envelope, explicit extension gaps');
